from metrics import calculate_metrics
import re


def extract_edges(dot):
    """Extract directed edges from Graphviz DOT code."""

    edges = set()

    quoted_pattern = r'"([^"]+)"\s*->\s*"([^"]+)"'

    for source, target in re.findall(quoted_pattern, dot):
        edges.add((source.strip(), target.strip()))

    unquoted_pattern = (
        r'(?<!")\b([A-Za-z_][A-Za-z0-9_]*)\b'
        r'\s*->\s*'
        r'\b([A-Za-z_][A-Za-z0-9_]*)\b'
    )

    for source, target in re.findall(unquoted_pattern, dot):
        edges.add((source.strip(), target.strip()))

    return edges


def extract_nodes(dot, edges):
    """Extract nodes from Graphviz DOT code."""

    nodes = set()

    # Every node appearing in an edge is a node
    for source, target in edges:
        nodes.add(source)
        nodes.add(target)

    # Quoted node declarations
    quoted_pattern = r'"([^"]+)"\s*(?:\[.*?\])?\s*;'

    for node in re.findall(quoted_pattern, dot, re.DOTALL):
        nodes.add(node.strip())

    # Unquoted node declarations
    unquoted_pattern = (
        r'(?<![-\w])'
        r'([A-Za-z_][A-Za-z0-9_]*)'
        r'\s*(?:\[.*?\])?\s*;'
    )

    for node in re.findall(unquoted_pattern, dot, re.DOTALL):
        if node not in {"digraph", "graph", "node", "edge"}:
            nodes.add(node.strip())

    return nodes


def evaluate_prediction(expected_nodes, expected_edges, predicted_dot):
    """
    Evaluate one LLM-generated DOT output.

    expected_nodes : ground-truth node set
    expected_edges : ground-truth edge set
    predicted_dot  : DOT generated by the LLM
    """

    predicted_edges = extract_edges(predicted_dot)

    predicted_nodes = extract_nodes(
        predicted_dot,
        predicted_edges
    )

    node_metrics = calculate_metrics(
        expected_nodes,
        predicted_nodes
    )

    edge_metrics = calculate_metrics(
        expected_edges,
        predicted_edges
    )

    return {
        "predicted_nodes": predicted_nodes,
        "predicted_edges": predicted_edges,
        "node_metrics": node_metrics,
        "edge_metrics": edge_metrics
    }